import {defaults} from './fixtures.mjs';
import assert from 'node:assert/strict';
import {reconcile,assignHosts,normalizeState,validateState} from '../model.mjs';
const c=defaults();c.hosts=[2,2,2];c.clusters=c.clusters.slice(0,1);c.clusters[0].profiles.worker.cpu=22;
const on=reconcile(c);assert.ok(on.vms.some(v=>v.host===null));
const off=assignHosts({...on,affinityEnabled:false});assert.ok(off.vms.every(v=>v.host!==null));validateState(off);
assert.deepEqual(normalizeState(JSON.parse(JSON.stringify(off))),off);
const moved=structuredClone(on),master=moved.vms.find(v=>v.type==='master'),ingress=moved.vms.find(v=>v.type==='ingress');const az=ingress.az;master.az=(master.az+1)%3;
const updated=assignHosts(moved);assert.equal(updated.vms.find(v=>v.id===ingress.id).az,az);validateState(updated);
assert.deepEqual(assignHosts({...off,affinityEnabled:true}),on);
const old=structuredClone(on);delete old.affinityEnabled;assert.equal(normalizeState(old).affinityEnabled,true);
assert.throws(()=>normalizeState({...off,affinityEnabled:'false'}),/on or off/);
assert.deepEqual(off.clusters,on.clusters);assert.deepEqual(off.host,on.host);
console.log('PASS: on enforces fit, off permits overcapacity, independent AZ moves, toggle repeatability, persistence and legacy defaults.');
